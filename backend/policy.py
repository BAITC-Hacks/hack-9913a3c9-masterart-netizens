def threshold(role: str, name: str) -> float:
    """Значение порога из единого реестра."""
    return THRESHOLDS[role][name]["value"]


def policy_payload() -> dict:
    """Раздел `policy` для analysis.json: правила, пороги, описание скоров и ограничения."""
    rules = [
        {
            "role": role,
            "label": ROLE_LABELS_RU[role],
            "description": RULE_DESCRIPTIONS_RU[role],
            "thresholds": {name: dict(spec) for name, spec in THRESHOLDS[role].items()},
        }
        for role in ROLE_PRECEDENCE
    ]
    return {
        "version": POLICY_VERSION,
        "rules": rules,
        "role_precedence": list(ROLE_PRECEDENCE),
        "role_tiers": [list(tier) for tier in ROLE_TIERS],
        "overlap_description": OVERLAP_DESCRIPTION_RU,
        "priority_description": PRIORITY_DESCRIPTION_RU,
        "priority_weights": dict(PRIORITY_WEIGHTS),
        "score_description": SCORE_DESCRIPTION_RU,
        "trace_horizon_depth": TRACE_HORIZON_DEPTH,
        "louvain": {"seed": LOUVAIN_SEED, "resolution": LOUVAIN_RESOLUTION},
        "limitations": list(LIMITATIONS_RU),
    }
